// Converts your Google Sheet export (.xlsx) into data/knowledge.js, which the chatbot reads.
// Usage: npm run build-kb -- path/to/RomSync_Chatbot_Knowledge_Base.xlsx
// Only rows whose Status is "Ready" (or "R") are included. Anything else is skipped.
import ExcelJS from 'exceljs';
import fs from 'node:fs';

const file = process.argv[2] || 'RomSync_Chatbot_Knowledge_Base.xlsx';
const wb = new ExcelJS.Workbook();
await wb.xlsx.readFile(file);

const text = (v) => {
  if (v == null) return '';
  if (typeof v === 'object') {
    if (v.richText) return v.richText.map((r) => r.text).join('').trim();
    if (v.text != null) return String(v.text).trim();
    if (v.result != null) return String(v.result).trim();
    return '';
  }
  return String(v).trim();
};
const rows = (name) => {
  const ws = wb.getWorksheet(name);
  if (!ws) throw new Error(`Missing sheet: "${name}"`);
  const out = [];
  ws.eachRow({ includeEmpty: false }, (row, n) => {
    if (n === 1) return;
    out.push(Array.from({ length: ws.columnCount }, (_, i) => text(row.getCell(i + 1).value)));
  });
  return out;
};
const ready = (s) => /^(r|ready)$/i.test(String(s).trim());
const num = (v) => { const n = parseFloat(String(v).replace(/[^0-9.]/g, '')); return Number.isFinite(n) ? n : null; };
const warn = [];

// Business Info + Bot Rules (Field | Value | Status)
const kv = (name) => Object.fromEntries(rows(name).filter((r) => r[0] && ready(r[2]) && r[1]).map((r) => [r[0], r[1]]));
const info = kv('Business Info');
const botRules = kv('Bot Rules');

// Services
const allSvc = rows('Services').filter((r) => r[0]);
const services = allSvc.filter((r) => ready(r[9])).map((r) => ({ id: r[0], name: r[1], category: r[2], what: r[3], bestFor: r[4], included: r[5], tools: r[6], timeline: r[7], price: num(r[8]) }));

// Pricing sheet has several blocks stacked in one tab
const packages = []; const addons = []; const terms = {}; const policy = [];
let mode = 'pkg';
for (const r of rows('Pricing')) {
  const a = r[0];
  if (!r.some(Boolean)) continue;
  if (/^add-ons$/i.test(a)) { mode = 'addons'; continue; }
  if (/^payment terms$/i.test(a)) { mode = 'terms'; continue; }
  if (/refund\s*&?\s*cancellation policy/i.test(a)) mode = 'policy';
  if (mode === 'pkg') { if (ready(r[6])) packages.push({ name: r[0], price: num(r[1]), scope: r[2], included: r[3], timeline: r[4], support: r[5] }); else warn.push(`Package "${r[0]}" skipped (status: ${r[6] || 'blank'})`); }
  else if (mode === 'addons') addons.push({ name: r[0], value: /rush/i.test(r[0]) && num(r[1]) < 1 ? `${Math.round(num(r[1]) * 100)}% surcharge on the project price` : `$${num(r[1])}`, note: /rush/i.test(r[0]) ? '' : r[2] });
  else if (mode === 'terms') terms[r[0]] = r[1];
  else policy.push(a);
}

// FAQ
const allFaq = rows('FAQ').filter((r) => r[2]);
const faq = allFaq.filter((r) => ready(r[6])).map((r) => ({ id: r[0], category: r[1], q: r[2], a: r[3], keywords: r[4], service: r[5], handoff: /^yes$/i.test(r[7]) }));

// Process
const process_ = rows('Process').filter((r) => r[1]).map((r) => ({ step: r[0], stage: r[1], what: r[2], client: r[3], time: r[4] }));

// Lead questions (the last row is usually a free-text note)
const lq = rows('Lead Questions');
const leadQuestions = lq.filter((r) => r[2]).map((r) => ({ question: r[0], why: r[1], field: r[2], required: /^yes$/i.test(r[3]) }));
const leadNote = (lq.find((r) => r[0] && !r[2]) || [''])[0];

// ---------- sanity checks (warnings only, nothing is changed) ----------
const min = num(info['Minimum project price']);
const moneyTexts = [...Object.values(botRules), leadNote, ...Object.entries(terms).map(([k, v]) => `${k}: ${v}`), ...faq.map((f) => f.a)];
for (const t of moneyTexts) {
  if (!/(start|minimum|under|above|from)/i.test(t)) continue;
  for (const m of t.matchAll(/\$\s?(\d[\d,]*)/g)) {
    const n = Number(m[1].replace(/,/g, ''));
    if (min && n !== min && n >= 50 && n <= 250) warn.push(`Price mismatch: minimum is $${min} but this text says $${n}: "${t.slice(0, 70)}..."`);
  }
}
for (const f of faq) if (!f.a) warn.push(`FAQ ${f.id} ("${f.q}") has no answer. The bot will use the policy sections or hand off.`);
const svcIds = new Set(allSvc.map((r) => r[0]));
for (const f of faq) if (f.service && /^S\d+$/.test(f.service) && !svcIds.has(f.service)) warn.push(`FAQ ${f.id} points to ${f.service}, which is not in Services`);
const skipped = allFaq.length - faq.length; if (skipped) warn.push(`${skipped} FAQ row(s) skipped because Status is not Ready`);
if (!policy.length) warn.push('No refund policy block found in the Pricing sheet.');

const kb = { info, services, packages, addons, terms, refundPolicy: policy.join('\n'), faq, process: process_, leadQuestions, leadNote, botRules };
fs.mkdirSync('data', { recursive: true });
fs.writeFileSync('data/knowledge.js', `// GENERATED by scripts/build-kb.mjs. Do not edit by hand; edit the spreadsheet and rebuild.\nexport default ${JSON.stringify(kb, null, 1)};\n`);
console.log(`knowledge.js written: ${services.length} services, ${packages.length} packages, ${faq.length} FAQ entries`);
if (warn.length) { console.log('\nWarnings:'); warn.forEach((w) => console.log(' - ' + w)); }
